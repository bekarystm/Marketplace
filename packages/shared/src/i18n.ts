const dictionaries: Record<Locale, Record<TranslationKey, string>> = { ru, kk };

export function translate(
  locale: Locale,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  let text = dictionaries[locale]?.[key] ?? ru[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

/** Pick the localized field of a record, e.g. localized(product, 'name', 'kk'). */
export function localized<T extends Record<string, unknown>>(
  record: T,
  field: string,
  locale: Locale,
): string {
  const value = record[`${field}_${locale}`] ?? record[`${field}_ru`];
  return typeof value === 'string' ? value : '';
}
